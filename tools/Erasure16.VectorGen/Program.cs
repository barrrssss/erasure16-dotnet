using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Erasure16;

namespace Erasure16.VectorGen
{
    /// <summary>
    /// Generates the canonical erasure16 conformance vectors (SPEC.md section 8) plus a
    /// MANIFEST.json index into a target directory given as the single command-line
    /// argument.
    ///
    /// Three kinds of vectors are emitted:
    ///   - field:       sample (a, b) -> mul(a, b) and a -> inv(a) checks.
    ///   - encode:      K, R, shardLen + K data shards -> expected R parity shards.
    ///   - reconstruct: K, R, shardLen + N shards + a present-mask (>= K true)
    ///                  -> expected fully reconstructed shard set.
    ///
    /// Shard data is stored as raw *.bin files; MANIFEST.json references each file with
    /// its byte length and SHA-256 digest. The generated bytes are fully determined: data
    /// shard contents come from a documented, implementation-independent PRNG (a 64-bit
    /// SplitMix64 keyed per case), so any implementation can regenerate identical files.
    /// </summary>
    internal static class Program
    {
        // Manifest schema version, so consumers can guard against format drift.
        private const int ManifestVersion = 2;

        private static int Main(string[] args)
        {
            if (args.Length != 1)
            {
                Console.Error.WriteLine("usage: Erasure16.VectorGen <output-directory>");
                Console.Error.WriteLine("  Writes *.bin vector files and MANIFEST.json into <output-directory>.");
                return 2;
            }

            string outDir = args[0];
            try
            {
                Generate(outDir);
            }
            catch (Exception ex)
            {
                Console.Error.WriteLine("vector generation failed: " + ex.Message);
                return 1;
            }

            return 0;
        }

        private static void Generate(string outDir)
        {
            Directory.CreateDirectory(outDir);

            var files = new List<ManifestFile>();
            var fieldCases = new List<object>();
            var encodeCases = new List<object>();
            var reconstructCases = new List<object>();

            // ---------------------------------------------------------------
            // FIELD vectors: explicit (a, b) -> mul and a -> inv samples.
            // ---------------------------------------------------------------
            var mulPairs = new (ushort A, ushort B)[]
            {
                (1, 1),
                (1, 0xFFFF),
                (2, 2),
                (2, 3),
                (0x8000, 2),
                (0x1234, 0x5678),
                (0xABCD, 0xFFFF),
                (0xFFFF, 0xFFFF),
                (0, 0x1234),
            };

            var mulSamples = new List<object>();
            foreach (var (a, b) in mulPairs)
            {
                ushort product = Gf16.Mul(a, b);
                mulSamples.Add(new
                {
                    a,
                    b,
                    product,
                });
            }

            var invInputs = new ushort[] { 1, 2, 3, 0x100, 0x8000, 0xABCD, 0xFFFE, 0xFFFF };
            var invSamples = new List<object>();
            foreach (ushort a in invInputs)
            {
                ushort inv = Gf16.Inv(a);
                invSamples.Add(new
                {
                    a,
                    inv,
                });
            }

            fieldCases.Add(new
            {
                name = "field-basic",
                reductionPolynomial = Gf16.ReductionPolynomial,
                generator = 2,
                mul = mulSamples,
                inv = invSamples,
            });

            // ---------------------------------------------------------------
            // ENCODE + RECONSTRUCT vectors.
            // Each encode case writes K data .bin files and R parity .bin files.
            // ---------------------------------------------------------------

            // (K, R, shardLen, prngSeed, present-mask-or-null-for-no-reconstruct, compact)
            //
            // Compact cases store their shards as two concatenated blobs and name the
            // absent indices instead of listing a full present mask (SPEC.md section 8.1).
            // Everything else keeps the one-file-per-shard layout, which is the readable
            // one at these sizes.
            var specs = new (string Name, int K, int R, int Len, ulong Seed, bool[] Present, bool Compact)[]
            {
                // K=4, R=2, len=8 - drop one data shard (index 0).
                ("enc-k4-r2-len8", 4, 2, 8, 0x1111_1111_1111_1111UL,
                    Mask(6, 0), false),

                // K=2, R=3, len=16 - R > K; drop both data shards (0 and 1).
                ("enc-k2-r3-len16", 2, 3, 16, 0x2222_2222_2222_2222UL,
                    Mask(5, 0, 1), false),

                // K=1, R=1, len=32 - minimal K; drop the only data shard.
                ("enc-k1-r1-len32", 1, 1, 32, 0x3333_3333_3333_3333UL,
                    Mask(2, 0), false),

                // K=32, R=8, len=64 - larger K; drop a mix of data + parity (8 total).
                ("enc-k32-r8-len64", 32, 8, 64, 0x4444_4444_4444_4444UL,
                    Mask(40, 0, 5, 10, 15, 20, 32, 36, 39), false),

                // K=3, R=0, len=24 - no parity output (encode produces no parity .bin).
                ("enc-k3-r0-len24", 3, 0, 24, 0x5555_5555_5555_5555UL,
                    null, false),

                // K=6410, R=1744, len=8 - a transport-scale configuration near the top of
                // the working-set envelope a memory-bounded consumer can afford, and the
                // only case above K=32. It is where the Cauchy construction is actually
                // stressed: the generator matrix has 11.2 million entries and the field
                // elements it indexes span most of GF(2^16), against 256 entries and a
                // handful of elements at K=32. 512 shards are dropped, 401 of them data,
                // so the E x E submatrix solve runs at a width no small case reaches.
                //
                // The shard length is deliberately short. Shards are combined word by
                // word, so shard length is independent of everything a large K and R
                // exercise, and 8 bytes keeps the committed blobs to 65 KB rather than
                // the megabytes a transport-sized shard would cost.
                ("enc-k6410-r1744-len8", 6410, 1744, 8, 0x6666_6666_6666_6666UL,
                    DroppedMask(6410 + 1744, 512, 0x7777_7777_7777_7777UL), true),
            };

            foreach (var spec in specs)
            {
                int n = spec.K + spec.R;

                // Build data shards from the documented PRNG.
                var shards = new byte[n][];
                var prng = new SplitMix64(spec.Seed);
                for (int i = 0; i < spec.K; i++)
                {
                    shards[i] = prng.NextBytes(spec.Len);
                }

                for (int p = 0; p < spec.R; p++)
                {
                    shards[spec.K + p] = new byte[spec.Len];
                }

                var rs = ReedSolomon16.Create(spec.K, spec.R);
                rs.Encode(shards);

                // Write the shard files: one per shard, or two concatenated blobs for a
                // compact case. At K=6410 the per-shard layout would be 8,154 files.
                var dataFiles = new List<string>();
                var parityFiles = new List<string>();
                string dataBlob = null;
                string parityBlob = null;

                if (spec.Compact)
                {
                    dataBlob = spec.Name + "-data.bin";
                    WriteBin(outDir, dataBlob, Concat(shards, 0, spec.K, spec.Len), files);

                    parityBlob = spec.Name + "-parity.bin";
                    WriteBin(outDir, parityBlob, Concat(shards, spec.K, spec.R, spec.Len), files);
                }
                else
                {
                    for (int i = 0; i < spec.K; i++)
                    {
                        string rel = spec.Name + "-data-" + i.ToString("D2", CultureInfo.InvariantCulture) + ".bin";
                        WriteBin(outDir, rel, shards[i], files);
                        dataFiles.Add(rel);
                    }

                    // Parity shard files (none when R == 0).
                    for (int p = 0; p < spec.R; p++)
                    {
                        string rel = spec.Name + "-parity-" + p.ToString("D2", CultureInfo.InvariantCulture) + ".bin";
                        WriteBin(outDir, rel, shards[spec.K + p], files);
                        parityFiles.Add(rel);
                    }
                }

                if (spec.Compact)
                {
                    encodeCases.Add(new
                    {
                        name = spec.Name,
                        k = spec.K,
                        r = spec.R,
                        shardLen = spec.Len,
                        dataBlob,
                        parityBlob,
                    });
                }
                else
                {
                    encodeCases.Add(new
                    {
                        name = spec.Name,
                        k = spec.K,
                        r = spec.R,
                        shardLen = spec.Len,
                        dataShards = dataFiles,
                        parityShards = parityFiles,
                    });
                }

                // Reconstruct case (when a present-mask is supplied).
                if (spec.Present != null)
                {
                    if (spec.Present.Length != n)
                    {
                        throw new InvalidOperationException(
                            "present mask length " + spec.Present.Length + " != N " + n + " for " + spec.Name);
                    }

                    // Sanity: at least K present, and at least one DATA shard dropped so
                    // the inversion path actually runs.
                    int presentCount = 0;
                    bool anyDataDropped = false;
                    for (int i = 0; i < n; i++)
                    {
                        if (spec.Present[i])
                        {
                            presentCount++;
                        }
                        else if (i < spec.K)
                        {
                            anyDataDropped = true;
                        }
                    }

                    if (presentCount < spec.K)
                    {
                        throw new InvalidOperationException("present mask has < K true for " + spec.Name);
                    }

                    if (!anyDataDropped)
                    {
                        throw new InvalidOperationException(
                            "reconstruct case " + spec.Name + " drops no data shard; decode path would be trivial");
                    }

                    // Verify the round-trip locally so a broken generator can't emit a
                    // bad "expected" set.
                    var working = new byte[n][];
                    for (int i = 0; i < n; i++)
                    {
                        working[i] = spec.Present[i] ? (byte[])shards[i].Clone() : null;
                    }

                    var presentCopy = (bool[])spec.Present.Clone();
                    rs.Reconstruct(working, presentCopy);
                    for (int i = 0; i < n; i++)
                    {
                        if (!BytesEqual(working[i], shards[i]))
                        {
                            throw new InvalidOperationException(
                                "self-check failed: reconstruct mismatch on shard " + i + " of " + spec.Name);
                        }
                    }

                    // The "expected" reconstructed set is just the full encoded set,
                    // which we already wrote above. Reference it as the expected full
                    // output to avoid duplicate bytes on disk.
                    if (spec.Compact)
                    {
                        var missing = new List<int>();
                        for (int i = 0; i < n; i++)
                        {
                            if (!spec.Present[i])
                            {
                                missing.Add(i);
                            }
                        }

                        reconstructCases.Add(new
                        {
                            name = spec.Name + "-recon",
                            k = spec.K,
                            r = spec.R,
                            shardLen = spec.Len,
                            missing, // absent indices, ascending; every other shard is present
                            expectedDataBlob = dataBlob,
                            expectedParityBlob = parityBlob,
                        });
                    }
                    else
                    {
                        var allFiles = new List<string>(dataFiles);
                        allFiles.AddRange(parityFiles);

                        reconstructCases.Add(new
                        {
                            name = spec.Name + "-recon",
                            k = spec.K,
                            r = spec.R,
                            shardLen = spec.Len,
                            present = spec.Present,
                            expectedShards = allFiles, // index order: data[0..K) then parity[0..R)
                        });
                    }
                }
            }

            // ---------------------------------------------------------------
            // MANIFEST.json
            // ---------------------------------------------------------------
            files.Sort((x, y) => string.CompareOrdinal(x.Path, y.Path));

            var manifest = new
            {
                manifestVersion = ManifestVersion,
                description = "erasure16 conformance vectors (GF(2^16) Cauchy Reed-Solomon). " +
                              "Data shard bytes are produced by a documented SplitMix64 PRNG; " +
                              "see Erasure16.VectorGen. Every implementation must reproduce these byte-for-byte.",
                field = fieldCases,
                encode = encodeCases,
                reconstruct = reconstructCases,
                files,
            };

            var options = new JsonSerializerOptions
            {
                WriteIndented = true,
                // Ensure the ManifestFile properties (Path/Length/Sha256) serialize as
                // camelCase (path/length/sha256), consistent with the anonymous case
                // objects above and with what the conformance tests read.
                PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
            };

            string json = JsonSerializer.Serialize(manifest, options);

            // Normalize to LF line endings regardless of host OS so the manifest bytes
            // are identical on every platform (System.Text.Json indents with the host
            // newline, which is CRLF on Windows). The committed vectors use LF.
            json = json.Replace("\r\n", "\n").Replace("\r", "\n");
            File.WriteAllText(Path.Combine(outDir, "MANIFEST.json"), json + "\n", new UTF8Encoding(false));

            Console.WriteLine("Wrote " + files.Count + " *.bin files + MANIFEST.json to " + outDir);
            foreach (var f in files)
            {
                Console.WriteLine("  " + f.Path + "  (" + f.Length + " bytes)");
            }
        }

        /// <summary>
        /// Concatenates <paramref name="count"/> equal-length shards starting at
        /// <paramref name="from"/>, in index order - the blob layout a compact case uses.
        /// </summary>
        private static byte[] Concat(byte[][] shards, int from, int count, int shardLen)
        {
            var blob = new byte[count * shardLen];
            for (int i = 0; i < count; i++)
            {
                Buffer.BlockCopy(shards[from + i], 0, blob, i * shardLen, shardLen);
            }

            return blob;
        }

        /// <summary>
        /// A present mask over <paramref name="n"/> shards with <paramref name="count"/> of
        /// them dropped, chosen from a fixed PRNG seed. Used where naming the dropped
        /// indices by hand would be unreadable; the chosen indices are recorded in the
        /// manifest, so no consumer has to reproduce this draw.
        /// </summary>
        private static bool[] DroppedMask(int n, int count, ulong seed)
        {
            var present = new bool[n];
            for (int i = 0; i < n; i++)
            {
                present[i] = true;
            }

            var prng = new SplitMix64(seed);
            int dropped = 0;
            while (dropped < count)
            {
                int index = (int)(prng.Next() % (ulong)n);
                if (present[index])
                {
                    present[index] = false;
                    dropped++;
                }
            }

            return present;
        }

        private static bool[] Mask(int n, params int[] dropped)
        {
            var present = new bool[n];
            for (int i = 0; i < n; i++)
            {
                present[i] = true;
            }

            foreach (int d in dropped)
            {
                present[d] = false;
            }

            return present;
        }

        private static void WriteBin(string outDir, string relativePath, byte[] data, List<ManifestFile> files)
        {
            string full = Path.Combine(outDir, relativePath);
            File.WriteAllBytes(full, data);

            using var sha = SHA256.Create();
            byte[] digest = sha.ComputeHash(data);

            files.Add(new ManifestFile
            {
                Path = relativePath,
                Length = data.Length,
                Sha256 = ToHex(digest),
            });
        }

        private static string ToHex(byte[] bytes)
        {
            var sb = new StringBuilder(bytes.Length * 2);
            foreach (byte b in bytes)
            {
                sb.Append(b.ToString("x2", CultureInfo.InvariantCulture));
            }

            return sb.ToString();
        }

        private static bool BytesEqual(byte[] a, byte[] b)
        {
            if (a == null || b == null)
            {
                return a == b;
            }

            if (a.Length != b.Length)
            {
                return false;
            }

            for (int i = 0; i < a.Length; i++)
            {
                if (a[i] != b[i])
                {
                    return false;
                }
            }

            return true;
        }

        private sealed class ManifestFile
        {
            public string Path { get; set; }

            public int Length { get; set; }

            public string Sha256 { get; set; }
        }
    }

    /// <summary>
    /// SplitMix64 PRNG (Vigna). Deterministic and implementation-independent so any
    /// language can reproduce the exact vector data shard bytes from the same seed.
    /// Bytes are emitted big-endian from each 64-bit output word, in order.
    /// </summary>
    internal sealed class SplitMix64
    {
        private ulong _state;

        public SplitMix64(ulong seed)
        {
            _state = seed;
        }

        public ulong Next()
        {
            unchecked
            {
                _state += 0x9E3779B97F4A7C15UL;
                ulong z = _state;
                z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9UL;
                z = (z ^ (z >> 27)) * 0x94D049BB133111EBUL;
                return z ^ (z >> 31);
            }
        }

        public byte[] NextBytes(int count)
        {
            var bytes = new byte[count];
            int i = 0;
            while (i < count)
            {
                ulong word = Next();
                for (int shift = 56; shift >= 0 && i < count; shift -= 8)
                {
                    bytes[i++] = (byte)(word >> shift);
                }
            }

            return bytes;
        }
    }
}
